package codetoanalyze.java.pulse;

import java.io.IOException;
import java.util.UUID;
import javax.servlet.ServletException;
import javax.servlet.http.HttpServlet;
import javax.servlet.http.HttpServletRequest;
import javax.servlet.http.HttpServletResponse;
import javax.servlet.http.HttpSession;

// The attributes of an HTTP session are trusted by the rest of the application, e.g. the "user"
// attribute is taken as the authenticated user. Storing data from the request there lets the client
// decide what the application trusts. The request handlers are inherited from HttpServlet, so the
// class names say whether they are expected to report.

class TrustBoundaryViolation {}

// the user name is stored before the password is checked
class RememberUserServletBad extends HttpServlet {

  @Override
  protected void doPost(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    request.getSession().setAttribute("user", request.getParameter("user"));
  }
}

// the client chooses which attribute is set, e.g. "isAdmin"
class FeatureFlagServletBad extends HttpServlet {

  @Override
  protected void doGet(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    request.getSession().setAttribute(request.getParameter("feature"), Boolean.TRUE);
  }
}

class LegacyCartServletBad extends HttpServlet {

  @Override
  protected void doPost(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    HttpSession session = request.getSession();
    session.putValue("cart", request.getParameter("cart"));
  }
}

class PreferencesServletBad extends HttpServlet {

  private static void remember(HttpSession session, String key, String value) {
    session.setAttribute(key, value);
  }

  @Override
  protected void doPost(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    remember(request.getSession(), "locale", request.getParameter("locale"));
  }
}

// the values stored in the session are generated by the server
class CsrfTokenServletOk extends HttpServlet {

  @Override
  protected void doGet(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    HttpSession session = request.getSession();
    session.setAttribute("csrfToken", UUID.randomUUID().toString());
    session.setAttribute("loginTime", System.currentTimeMillis());
  }
}

interface UserStore {
  boolean checkPassword(String user, String password);
}

// The user name is only stored once the password has been checked against the user store.
// Infer cannot know what `checkPassword` checks: the taint config of these tests declares it as a
// sanitizer of kind `Validation`, which the "Trust Boundary Violation" policy accepts, as a project
// would do for its own validation methods.
class LoginServletOk extends HttpServlet {

  UserStore users;

  @Override
  protected void doPost(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    String user = request.getParameter("user");
    if (!users.checkPassword(user, request.getParameter("password"))) {
      response.setStatus(401);
      return;
    }
    request.getSession().setAttribute("user", user);
  }
}

// The sanitizer applies to the user name as soon as `checkPassword` is called, whatever it returns,
// so ignoring the result of the check is not reported.
class FN_IgnoredPasswordCheckServletBad extends HttpServlet {

  UserStore users;

  @Override
  protected void doPost(HttpServletRequest request, HttpServletResponse response)
      throws ServletException, IOException {
    String user = request.getParameter("user");
    users.checkPassword(user, request.getParameter("password"));
    request.getSession().setAttribute("user", user);
  }
}
